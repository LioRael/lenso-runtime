"""Generate typed Python bindings from the same business-local v1 JSON contract.

Usage: python -m lenso_runtime.generate contract.json output.py [client_name]
"""
from __future__ import annotations

import argparse
import json
import keyword
from pathlib import Path
from typing import Any

from .schema import Contract, Schema, validate_contract


def generate(contract: Contract, name: str = "logs") -> str:
    validate_contract(contract)
    if not name.isascii() or not name.isidentifier() or keyword.iskeyword(name):
        raise ValueError("invalid client name")
    definitions: list[str] = []
    names = {"CONTRACT", "RuntimeHost", "ResponseStream", "Target", "TypedDict", "NotRequired", "Literal", "Any", "cast", "json"}

    def pascal(value: str) -> str:
        return "".join(word[:1].upper() + word[1:] for word in value.split("_"))

    def reserve(ident: str) -> None:
        if ident in names or not ident.isidentifier() or keyword.iskeyword(ident):
            raise ValueError(f"generated type name collision: {ident}")
        names.add(ident)

    client_name = pascal(name) + "Client"
    reserve(client_name)

    def render(schema: Schema, ident: str) -> str:
        if "anyOf" in schema:
            branch = next(b for b in schema["anyOf"] if b["type"] != "null")
            return render(branch, ident + "Value") + " | None"
        if "enum" in schema and schema["type"] != "number":
            # Literal does not support float values; numeric bounds stay runtime checked.
            return "Literal[" + ", ".join(repr(v) for v in schema["enum"]) + "]"
        kind = schema["type"]
        if kind == "array":
            return "list[" + render(schema["items"], ident + "Item") + "]"
        if kind == "object":
            reserve(ident)
            fields = []
            for key, child in schema["properties"].items():
                if not key.isascii() or not key.isidentifier():
                    raise ValueError(f"unsupported generated property: {key}")
                result = render(child, ident + pascal(key))
                if key not in schema["required"]:
                    result = f"NotRequired[{result}]"
                fields.append(f"    {key!r}: {result},")
            definitions.append(f"{ident} = TypedDict({ident!r}, {{\n" + "\n".join(fields) + "\n})")
            return ident
        return {"string": "str", "boolean": "bool", "number": "float", "integer": "int", "null": "None"}[kind]

    methods = []
    for method, definition in contract["methods"].items():
        if (not method.isascii() or not method.isidentifier() or keyword.iskeyword(method)
                or method.startswith("_") or method in {"host", "target"}):
            raise ValueError(f"unsupported generated method: {method}")
        prefix = pascal(method)
        for slot in ("input", "output", "error"):
            ident = prefix + pascal(slot)
            result = render(definition[slot], ident)
            if result != ident:
                reserve(ident)
                definitions.append(f"{ident} = {result}")
        options = "*, timeout_ms: int = 5000, trace_id: str | None = None, parent_id: str | None = None"
        arguments = (f"self.target, {method!r}, input, timeout_ms=timeout_ms, "
                     f"trace_id=trace_id, parent_id=parent_id, contract=CONTRACT['methods'][{method!r}]")
        if definition["mode"] == "unary":
            methods.append(f"    async def {method}(self, input: {prefix}Input, {options}) -> {prefix}Output:\n"
                           f"        return cast({prefix}Output, await self.host.call({arguments}))")
        else:
            methods.append(f"    def {method}(self, input: {prefix}Input, {options}) -> ResponseStream[{prefix}Output]:\n"
                           f"        return self.host.stream({arguments})")
    return ("# Generated by python -m lenso_runtime.generate. Do not edit.\n"
            "from __future__ import annotations\n\nimport json\n"
            "from typing import Any, Literal, NotRequired, TypedDict, cast\n"
            "from lenso_runtime import ResponseStream, RuntimeHost, Target\n\n"
            f"CONTRACT = json.loads({json.dumps(contract, ensure_ascii=True, separators=(',', ':'))!r})\n\n"
            + "\n\n".join(definitions) + "\n\n"
            f"class {client_name}:\n"
            "    def __init__(self, host: RuntimeHost, *, namespace: str, service: str):\n"
            "        self.host = host\n"
            "        self.target = Target(namespace, service, CONTRACT['version'])\n\n"
            + "\n\n".join(methods) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("contract", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("client_name", nargs="?", default="logs")
    args = parser.parse_args()
    output = generate(json.loads(args.contract.read_text()), args.client_name)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
